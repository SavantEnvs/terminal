#!/usr/bin/env python3
"""Generate TilFeatureStaging.h from src/features.xml (the Linux equivalent of
tools/Generate-FeatureStagingHeader.ps1, Dev branding, no branch overrides)."""
import sys
import xml.etree.ElementTree as ET

src, out = sys.argv[1], sys.argv[2]
ns = {"f": "http://microsoft.com/TilFeatureStaging-Schema.xsd"}
root = ET.parse(src).getroot()
lines = ["// generated by mayhem/gen_features.py from src/features.xml", "#pragma once"]
for feat in sorted(root.findall("f:feature", ns), key=lambda e: e.find("f:name", ns).text):
    name = feat.find("f:name", ns).text
    stage = feat.find("f:stage", ns).text
    for tok in feat.findall("f:alwaysEnabledBrandingTokens/f:brandingToken", ns):
        if tok.text == "Dev":
            stage = "AlwaysEnabled"
    for tok in feat.findall("f:alwaysDisabledBrandingTokens/f:brandingToken", ns):
        if tok.text == "Dev":
            stage = "AlwaysDisabled"
    enabled = "true" if stage == "AlwaysEnabled" else "false"
    lines.append(f"struct {name} {{ static constexpr bool IsEnabled() {{ return {enabled}; }} }};")
with open(out, "w") as fh:
    fh.write("\n".join(lines) + "\n")
